const topicContent = `The basics lesson gave you the three-stage sketch: placement, layering, integration.
This lesson is what you do when a real file refuses to sit in one box. Criminals do not
file a cover sheet announcing which stage they are in. They move value until the story
of the money is harder to tell than the story of the crime that produced it.

Your job is not to recite the model. Your job is to say which movement the records
support, which label is still a hypothesis, and what would prove you wrong.


The placement-layering-integration sequence is a teaching model. It is useful because
it forces a question: where did value enter a channel that looks legitimate, how was
the trail confused, and where did it become spendable. It is not a statute, and it is
not a promise that every scheme will show you three neat chapters.

### Overlap is normal

A single transaction can do two jobs. A cash purchase of property can be placement and
integration in the same afternoon. An invoice that never matched a shipment can layer
funds and, once the payment lands in a trading company, look like ordinary revenue.
If you force every hop into exactly one stage, you will write a tidy paragraph and a
wrong one.

### Predicate offense and laundering are different facts

The predicate offense is the crime that produced the value: fraud, trafficking,
corruption, extortion, or something else you can name. Laundering is what was done to
the proceeds so they could be held or spent with less friction. You can often see the
financial movement before anyone has proved the predicate. Say that plainly. "The
flow is consistent with layering" is an analytic judgment. "This person committed
fraud" is a different claim, and it needs its own evidence.

### Professional distance

Many schemes are a service. The person who committed the predicate offense may never
touch the accounts that do the layering. A consultant, a trading company, or a
money-service business may be the part you can see. Map the service. Do not assume
the name on the account is the name on the crime.


Placement is the moment illicit value enters a channel that has a legitimate excuse
to exist: a bank, a money transmitter, a casino, a cash business, a courier who will
carry it across a border. It is often the noisiest stage, because cash and first
deposits still have to meet a human, a form, or a threshold.

### What the record tends to show

- **A weak story for the cash.** The deposit, the buy-in, or the till does not match the business you can see: foot traffic, staff, inventory, or the customer's known work.
- **Commingling.** Illicit cash dropped into a stream that also contains real customers. The legitimate revenue is the camouflage. Your question is proportion, not whether the shop exists.
- **Channel shopping.** The same beneficial party using many branches, many transmitters, or many night drops so no single teller sees the whole amount.
- **A first hop that is also a conversion.** Cash to chips, cash to a stored-value product, cash to a third party's account. Conversion is not sophistication. It is still placement if this is where the value entered.

### Structuring is a pattern, not a single deposit

You already know that reporting thresholds exist and that people try to sit under them.
Here is the analytic rule: one deposit below a threshold is ordinary life. A repeated
pattern of amounts, locations, and timing, with no business reason, is the lead.
Describe the pattern: who, where, how often, how close to the line, and what the
account did next. A list of near-threshold deposits with no comparison to the
customer's normal behavior is a spreadsheet, not an assessment.

If the only interesting fact is "the amount was under the reporting line," you do not
have a case. You have a number that also describes most of the country buying a used car.


Layering is the attempt to break the audit trail. The money is already in a channel.
Now it moves through hops, labels, and jurisdictions until a reader gets tired. Profit
is not the point of this stage. Distance is.

### What you actually chart

- **Hops.** Each transfer is a row: date, amount, origin, destination, stated purpose.
- **Labels.** The same value called a loan, then an investment, then a consulting fee. The label change is the layer.
- **Jurisdictions.** A hop into a place where ownership records are thin is a fact about the trail, not a moral verdict on the country.
- **Time.** Very fast pass-throughs, and long pauses that exist only to look patient, both matter. Note which one you have.

### Round-tripping

Round-tripping is value that leaves and comes home wearing a new story. A person
sends funds to a company they control, and the company sends the funds back as a loan,
a dividend, or an invoice payment. On paper there is a counterparty. In substance
there is a mirror. You are looking for common control, not for a famous island.

### Complexity is not proof

A twelve-hop path is a reason to keep reading. It is not, by itself, a finding of
laundering. Legitimate treasury operations are also ugly: netting, cash pooling,
tax withholding, and escrow all produce hops that look theatrical if you have never
seen a real finance department. The question is whether each hop has a commercial
reason you can check. If the reason is "consulting" and nobody can name the advice,
the label is the weakness. Write that.


Integration is the stage where the value can be spent, invested, or shown in public
without an obvious link to the predicate offense. It often looks dull. Dull is the
product the launderer paid for.

### Forms you will actually meet

- **Assets.** Property, vehicles, art, and company shares bought with funds whose origin you cannot tie to income.
- **A business that is real enough to file.** The company has a lease and a logo. The question is whether the profits match the trade, or whether the trade exists to explain the profits.
- **Loan-back.** Funds return as a loan from an entity the subject controls or can influence. Repayments then look like ordinary debt service. Ask who funded the lender.
- **Lifestyle gap.** Declared income, known occupation, and the assets in front of you do not belong in the same paragraph. The gap is the lead. The explanation, if it exists, will be specific: an inheritance, a sale, a spouse's business. Vague wealth is not an explanation.

Integration is where analysts get bored and criminals get comfortable. Boredom is not
a finding either. If the assets match a documented sale of a prior business, say so
and stop performing suspicion.


When you brief, separate the movement from the label.

- **Movement.** What value moved, from whom, to whom, when, and under what stated purpose.
- **Stage hypothesis.** Which stage best describes that movement, and why.
- **Overlap.** If two stages fit, say both, and say which part of the transaction does which job.
- **Falsifier.** The document or fact that would collapse the hypothesis: a real inventory count, a genuine loan agreement with an unrelated lender, a customer base that explains the cash.

Do not decorate one wire transfer with all three stage names because the model has
three names. Pick the judgment the records will carry. Park the rest as hypotheses
with a collection need.

A useful sentence sounds like this: "The cash deposits are consistent with placement
into a commingled business account. The same-week wires to two newly formed companies,
both invoiced as consulting, are a layering hypothesis. Integration is not shown.
We do not have the asset purchases or the ownership of the recipients."

That paragraph can survive a question. "They are laundering" cannot.


Some schemes barely use the textbook sequence.

- **Trade.** An invoice can place, layer, and book false revenue without a suitcase. That problem has its own lesson, because the documents lie in a different way than a cash deposit does.
- **Compressed hops.** A conversion into a digital asset, a pass through one or two services, and a conversion back can do a lot of distance in a short time. The stages are still a lens. The timeline is just ruder.
- **Service providers.** If the subject paid a specialist, you may see integration (the lifestyle) and never see the placement. Task the missing chapter. Do not invent it.

The model fails in one other way: it tempts you to tell a story with a beginning,
a middle, and an end. Intelligence files are often a middle. Brief the middle.


**Scenario.** A logistics clerk's personal account receives twelve incoming transfers
in five weeks from four companies that share a formation agent and a virtual office.
Each transfer is described as "reimbursement." The next day, in every case, ninety
percent leaves to a property solicitor for a deposit on a flat the clerk is buying.
The clerk's salary has not changed. Two of the sending companies have no website,
no staff listed in the registry, and invoices on file for "market research" with no
description of the research.

**Write four short paragraphs:**

- What movement is actually on the page.
- Which stage label you will use for the incoming transfers, and which label you will use for the payment to the solicitor. If you use two, say why both fit.
- The single fact that would make this ordinary reimbursement rather than a layering hypothesis.
- The two records you would ask for next, and what each one would decide.

If your answer uses the phrase "classic integration" for the incoming wire and never
mentions the flat, read the dates again. The flat is doing something. The wire is
doing something else.`

